#!/bin/bash
# RHL9-49 | Ensure GDM login banner is configured
# Test Method: Manual

{
   echo -e "\n- Audit Result:\n  ** MANUAL REVIEW REQUIRED **"
   echo -e "\n- Test Procedure:"
   echo -e "  Perform an automated test using the current Nessus Profile provided by the IRS Office of Safeguards website or from a SSH session run the following script  to verify that the text banner on the login screen is enabled and set:"
   echo -e "  "
   echo -e "  \`\`\`"
   echo -e "  #!/usr/bin/env bash"
   echo -e "  "
   echo -e "  {"
   echo -e "   l_pkgoutput=\"\""
   echo -e "   if command -v dpkg-query > /dev/null 2> then"
   echo -e "   l_pq=\"dpkg-query -W\""
   echo -e "   elif command -v rpm > /dev/null 2> then"
   echo -e "   l_pq=\"rpm -q\""
   echo -e "   fi"
   echo -e "   l_pcl=\"gdm gdm3\" # Space separated list of packages to check"
   echo -e "   for l_pn in \$l_pcl; do"
   echo -e "   \$l_pq \"\$l_pn\" > /dev/null 2>&1 && l_pkgoutput=\"\$l_pkgoutput\n - Package: \\"\$l_pn\\" exists on the system\n - checking configuration\""
   echo -e "   done"
   echo -e "   if [ -n \"\$l_pkgoutput\" ]; then"
   echo -e "   l_output=\"\" l_output2=\"\""
   echo -e "   echo -e \"\$l_pkgoutput\""
   echo -e "   # Look for existing settings and set variables if they exist"
   echo -e "   l_gdmfile=\"\$(grep -Prils '^\h*banner-message-enable\b' /etc/dconf/db/*.d)\""
   echo -e "   if [ -n \"\$l_gdmfile\" ]; then"
   echo -e "   # Set profile name based on dconf db directory ({PROFILE_NAME}.d)"
   echo -e "   l_gdmprofile=\"\$(awk -F\/ '{split(\$(NF-1),a,\".\");print a[1]}' <<< \"\$l_gdmfile\")\""
   echo -e "   # Check if banner message is enabled"
   echo -e "   if grep -Pisq '^\h*banner-message-enable=true\b' \"\$l_gdmfile\"; then"
   echo -e "   l_output=\"\$l_output\n - The \\"banner-message-enable\\" option is enabled in \\"\$l_gdmfile\\"\""
   echo -e "   else"
   echo -e "   l_output2=\"\$l_output2\n - The \\"banner-message-enable\\" option is not enabled\""
   echo -e "   fi"
   echo ""
}
