#!/bin/bash
# RHL9-184 | Ensure SUID and SGID files are reviewed
# Test Method: Manual

{
   echo -e "\n- Audit Result:\n  ** MANUAL REVIEW REQUIRED **"
   echo -e "\n- Test Procedure:"
   echo -e "  Run the following script to generate a list of SUID and SGID files:"
   echo -e "  "
   echo -e "  \`\`\`"
   echo -e "  #!/usr/bin/env bash"
   echo -e "  "
   echo -e "  {"
   echo -e "   l_output=\"\" l_output2=\"\""
   echo -e "   a_suid=(); a_sgid=() # initialize arrays"
   echo -e "   while IFS= read -r l_mount; do"
   echo -e "   while IFS= read -r -d \$'\0' l_file; do"
   echo -e "   if [ -e \"\$l_file\" ]; then"
   echo -e "   l_mode=\"\$(stat -Lc '%#a' \"\$l_file\")\""
   echo -e "   [ \$(( \$l_mode & 04000 )) -gt 0 ] && a_suid+=(\"\$l_file\")"
   echo -e "   [ \$(( \$l_mode & 02000 )) -gt 0 ] && a_sgid+=(\"\$l_file\")"
   echo -e "   fi"
   echo -e "   done < <(find \"\$l_mount\" -xdev -type f \( -perm -2000 -o -perm -4000 \) -print0 2>/dev/null)"
   echo -e "   done < <(findmnt -Dkerno fstype,target,options | awk '(\$1 !~ /^\s*(nfs|proc|smb|vfat|iso9660|efivarfs|selinuxfs)/ && \$2 !~ /^\/run\/user\// && \$3 !~/noexec/ && \$3 !~/nosuid/) {print \$2}')"
   echo -e "   if ! (( \${#a_suid[@]} > 0 )); then"
   echo -e "   l_output=\"\$l_output\n - No executable SUID files exist on the system\""
   echo -e "   else"
   echo -e "   l_output2=\"\$l_output2\n - List of \\"\$(printf '%s' \"\${#a_suid[@]}\")\\" SUID executable files:\n\$(printf '%s\n' \"\${a_suid[@]}\")\n - end of list -\n\""
   echo -e "   fi"
   echo -e "   if ! (( \${#a_sgid[@]} > 0 )); then"
   echo -e "   l_output=\"\$l_output\n - No SGID files exist on the system\""
   echo -e "   else"
   echo -e "   l_output2=\"\$l_output2\n - List of \\"\$(printf '%s' \"\${#a_sgid[@]}\")\\" SGID executable files:\n\$(printf '%s\n' \"\${a_sgid[@]}\")\n - end of list -\n\""
   echo -e "   fi"
   echo -e "   [ -n \"\$l_output2\" ] && l_output2=\"\$l_output2\n- Review the preceding list(s) of SUID and/or SGID files to\n- ensure that no rogue programs have been introduced onto the system.\n\" "
   echo -e "   unset a_arr; unset a_suid; unset a_sgid # Remove arrays"
   echo -e "   # If l_output2 is empty, Nothing to report"
   echo ""
}
