#!/bin/bash
# RHL9-207 | Ensure unused filesystems kernel modules are not available
# Test Method: Manual

{
   echo -e "\n- Audit Result:\n  ** MANUAL REVIEW REQUIRED **"
   echo -e "\n- Test Procedure:"
   echo -e "  Run the following script to:"
   echo -e "  - Look at the filesystem kernel modules available to the currently running kernel."
   echo -e "  - Exclude mounted filesystem kernel modules that don't currently have a CVE"
   echo -e "  - List filesystem kernel modules that are not fully disabled, or are loaded into the kernel"
   echo -e "  "
   echo -e "  Review the generated output"
   echo -e "  "
   echo -e "  \`\`\` "
   echo -e "  #! /usr/bin/env bash"
   echo -e "  "
   echo -e "  {"
   echo -e "   a_output=(); a_output2=(); a_modprope_config=(); a_excluded=(); a_available_modules=()"
   echo -e "   a_ignore=(\"xfs\" \"vfat\" \"ext2\" \"ext3\" \"ext4\")"
   echo -e "   a_cve_exists=(\"afs\" \"ceph\" \"cifs\" \"exfat\" \"ext\" \"fat\" \"fscache\" \"fuse\" \"gfs2\" \"nfs_common\" \"nfsd\" \"smbfs_common\")"
   echo -e "   f_module_chk()"
   echo -e "   {"
   echo -e "   l_out2=\"\"; grep -Pq -- \"\b\$l_mod_name\b\" <<< \"\${a_cve_exists[*]}\" && l_out2=\" <- CVE exists!\""
   echo -e "   if ! grep -Pq -- '\bblacklist\h+'\"\$l_mod_name\"'\b' <<< \"\${a_modprope_config[*]}\"; then"
   echo -e "   a_output2+=(\" - Kernel module: \\"\$l_mod_name\\" is not fully disabled \$l_out2\")"
   echo -e "   elif ! grep -Pq -- '\binstall\h+'\"\$l_mod_name\"'\h+\/bin\/(false|true)\b' <<< \"\${a_modprope_config[*]}\"; then"
   echo -e "   a_output2+=(\" - Kernel module: \\"\$l_mod_name\\" is not fully disabled \$l_out2\")"
   echo -e "   fi"
   echo -e "   if lsmod | grep \"\$l_mod_name\" &> /dev/null; then # Check if the module is currently loaded"
   echo -e "   l_output2+=(\" - Kernel module: \\"\$l_mod_name\\" is loaded\" \"\")"
   echo -e "   fi"
   echo -e "   }"
   echo -e "   while IFS= read -r -d \$'\0' l_module_dir; do"
   echo -e "   a_available_modules+=(\"\$(basename \"\$l_module_dir\")\")"
   echo -e "   done < <(find \"\$(readlink -f /lib/modules/\"\$(uname -r)\"/kernel/fs)\" -mindepth 1 -maxdepth 1 -type d ! -empty -print0)"
   echo -e "   while IFS= read -r l_exclude; do"
   echo ""
}
